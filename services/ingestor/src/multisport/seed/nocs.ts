function toSeed(row: Row, kind: NocKind, panam: boolean): NocSeed {
  const [code, iso3, iso2, en, pt, es] = row;
  return {
    code,
    iso3,
    iso2,
    name: { en, 'pt-BR': pt, es },
    kind,
    iocMember: kind === 'noc',
    panamMember: panam,
  };
}

